/**
 * The sample shop: categories, brands and products with realistic Bangladeshi prices (taka).
 * Used by `npm run db:seed-demo` so the admin panel and website have something to show.
 */

export interface DemoCategory {
  name: string;
  icon: string;
  description?: string;
  children?: DemoCategory[];
}

export interface DemoBrand {
  name: string;
  /** Short code for SKUs. */
  code: string;
  color: string;
  featured?: boolean;
  description: string;
}

export interface DemoProduct {
  name: string;
  /** Category name (must exist in DEMO_CATEGORIES or already in the database). */
  category: string;
  brand?: string;
  icon: string;
  price: number;
  wholesale?: number;
  cost?: number;
  sale?: number;
  /** Stock for every variant, or one number per variant. Leave out to not track stock. */
  stock?: number | number[];
  lowStock?: number;
  status?: 'draft' | 'active' | 'archived';
  short: string;
  description: string;
  tags?: string[];
  specs?: [string, string][];
  options?: { name: string; values: string[] }[];
  /** Price per variant, by its label ("Black", "A4 / Ruled"). Others use `price`. */
  variantPrices?: Record<string, number>;
  weight?: number;
}

