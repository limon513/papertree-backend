/** "spiral-notepad" -> "Spiral Notepad". */
export function iconLabel(key: string) {
  return LABELS[key] ?? key.replace(/(^|-)(\w)/g, (_m, dash: string, c: string) => (dash ? ' ' : '') + c.toUpperCase());
}
